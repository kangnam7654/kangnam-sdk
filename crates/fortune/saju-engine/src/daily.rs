/// 풀에서 `seed` 기반으로 결정적 select. 같은 (rel, elem, seed)는 항상 같은 변형.
/// seed는 호출처에서 (year, month, day) 등으로 만들어 하루 단위로 변형이 회전.
fn health_advice_pair(relation: ElementRelation, elem: Element, seed: u64) -> AdvicePair {
    let pool = health_advice_pool(relation, elem);
    pool[(seed as usize) % pool.len()]
}

/// 날짜 기반 결정적 seed. (year, month, day) 조합으로 매일 다른 값을 만들고
/// 같은 날짜는 항상 같은 값. 풀 인덱스 % pool.len()으로 사용되므로 hash 강도는
/// 중요하지 않음.
fn ymd_seed(year: i32, month: u32, day: u32) -> u64 {
    (year as u64)
        .wrapping_mul(10_000)
        .wrapping_add(month as u64 * 100)
        .wrapping_add(day as u64)
}

