    #[test]
    fn health_advice_pool_all_variants_unique_and_well_sized() {
        // 풀 전체의 모든 (short, full) 텍스트가 유일해야 — 변형 간 중복은 사용자에게
        // "다른 변형인 척하는 같은 멘트"로 보이므로 카피 작성 실수 방지.
        // 또한 short ≤ 80자, full ≥ 100자 규격 회귀 lock.
        use std::collections::HashSet;
        let mut shorts = HashSet::new();
        let mut fulls = HashSet::new();
        let mut total = 0;
        for elem in all_elements() {
            for rel in all_relations() {
                let pool = health_advice_pool(rel, elem);
                for (s, f) in pool {
                    assert!(!s.is_empty(), "empty short for ({:?}, {:?})", elem, rel);
                    assert!(!f.is_empty(), "empty full for ({:?}, {:?})", elem, rel);
                    assert!(
                        s.chars().count() <= 80,
                        "short too long ({} chars) for ({:?}, {:?}): {}",
                        s.chars().count(),
                        elem,
                        rel,
                        s,
                    );
                    assert!(
                        f.chars().count() >= 100,
                        "full too short ({} chars) for ({:?}, {:?}): {}",
                        f.chars().count(),
                        elem,
                        rel,
                        f,
                    );
                    shorts.insert(*s);
                    fulls.insert(*f);
                    total += 1;
                }
            }
        }
        // 풀 전체 변형 수만큼 unique short/full이 모여야 (중복 0).
        assert_eq!(shorts.len(), total, "duplicate short variants in pool");
        assert_eq!(fulls.len(), total, "duplicate full variants in pool");
        // 매트릭스 자체는 최소 25 (셀당 1개 보장).
        assert!(total >= 25, "expected >= 25 total variants, got {}", total);
    }

